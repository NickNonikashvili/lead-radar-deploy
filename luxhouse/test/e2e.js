// The 3D viewer is tested against real tours when they exist. Until then a small synthetic
// tour (exact geometry, generated by tools/tour/build_tour.py --fixture) is installed for the run.
const FIXTURE = path.join(__dirname, "fixtures", "tour");
let fixtureDir = null;
function installTourFixture() {
  if (listings.all().some((l) => l.hasTour)) return;
  const slug = listings.all()[0].slug;
  fixtureDir = path.join(config.root, "public", "media", "listings", slug, "tour");
  fs.cpSync(FIXTURE, fixtureDir, { recursive: true });
}
function removeTourFixture() {
  if (fixtureDir) fs.rmSync(fixtureDir, { recursive: true, force: true });
  fixtureDir = null;
}
process.on("exit", removeTourFixture);

const results = [];
async function step(name, fn) {
  try {
    await fn();
    results.push({ name, ok: true });
    console.log("  ok   " + name);
  } catch (err) {
    results.push({ name, ok: false, err });
    console.log("  FAIL " + name + "\n       " + String(err && err.message).split("\n").join("\n       "));
  }
}

