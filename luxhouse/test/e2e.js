    await page.locator("[data-error]").waitFor({ state: "visible" });
    await page.unroute("**/geo.bin");
    expectingFailure = false;
    await page.locator("[data-retry]").click();
    await ready();
    assert.ok(await page.locator("[data-error]").isHidden());
