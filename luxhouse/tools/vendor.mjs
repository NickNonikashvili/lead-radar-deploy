#!/usr/bin/env node
/**
 * Copy third-party browser assets out of node_modules into public/vendor and
 * bundle the 3D tour viewer, so the deployed site serves everything itself
 * (no CDN requests, no build step on the host).
 *
 *   npm run vendor                 every step
 *   node tools/vendor.mjs fonts    only the named steps: fonts, leaflet, tour
 *
 * Outputs (all committed to the repository):
 *   public/vendor/fonts/*.woff2 + fonts.css
 *   public/vendor/leaflet/{leaflet.js,leaflet.css,images/*}
 *   public/js/tour.bundle.js   (three.js + viewer, minified)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const NM = path.join(ROOT, "node_modules");
const VENDOR = path.join(ROOT, "public", "vendor");

// ---------------------------------------------------------------- fonts
// Nocturne sets everything in one grotesque: Inter Tight for display and interface, Inter for
// running text, Noto Sans Georgian for Mkhedruli (its "standard" build carries the weight and the
// width axis, which the Georgian display sizes draw in to sit beside Inter Tight).
// The layout preloads `<family>-<subset>-<axes>-normal.woff2` by name: see views/layout.ejs.
const FONT_SOURCES = [
  // [package, css files, subsets to keep]
  ["@fontsource-variable/inter-tight", ["wght.css"], ["latin", "latin-ext", "cyrillic", "cyrillic-ext"]],
  ["@fontsource-variable/inter", ["wght.css"], ["latin", "latin-ext", "cyrillic", "cyrillic-ext"]],
  ["@fontsource-variable/noto-sans-georgian", ["standard.css"], ["georgian"]],
];

function buildFonts() {
  const outDir = path.join(VENDOR, "fonts");
  fs.mkdirSync(outDir, { recursive: true });
  let css = "/* Generated by tools/vendor.mjs from @fontsource packages (SIL Open Font License). Do not edit. */\n";
  const kept = new Set(["fonts.css"]);
  for (const [pkg, files, subsets] of FONT_SOURCES) {
    for (const f of files) {
      const src = fs.readFileSync(path.join(NM, pkg, f), "utf8");
      // Each block is preceded by a comment naming its subset, e.g. /* inter-tight-latin-wght-normal */
      const blocks = src.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) || [];
      for (const block of blocks) {
        const m = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/);
        if (!m) continue;
        const file = m[1];
        const subset = subsets.find((s) => new RegExp(`-${s}-(?:\\d|wght|standard)`).test(file));
        if (!subset) continue;
        fs.copyFileSync(path.join(NM, pkg, "files", file), path.join(outDir, file));
        kept.add(file);
        const face = block
          .replace(/\/\*[^*]*\*\/\s*/, "")
          // The stylesheets name the families plainly: "Inter Tight", "Inter", "Noto Sans Georgian".
          .replace(/(font-family:\s*'[^']*?) Variable'/, "$1'")
          .replace(/src:[^;]*;/, `src: url(/vendor/fonts/${file}) format('woff2');`);
        css += face + "\n";
      }
    }
  }
  fs.writeFileSync(path.join(outDir, "fonts.css"), css);
  // Faces of typefaces the site no longer uses must not stay behind.
  for (const f of fs.readdirSync(outDir)) {
    if (!kept.has(f)) fs.unlinkSync(path.join(outDir, f));
  }
  return kept.size - 1;
}

// ---------------------------------------------------------------- leaflet
function buildLeaflet() {
  const src = path.join(NM, "leaflet", "dist");
  const out = path.join(VENDOR, "leaflet");
  fs.mkdirSync(path.join(out, "images"), { recursive: true });
  fs.copyFileSync(path.join(src, "leaflet.js"), path.join(out, "leaflet.js"));
  fs.copyFileSync(path.join(src, "leaflet.css"), path.join(out, "leaflet.css"));
  for (const f of fs.readdirSync(path.join(src, "images"))) {
    fs.copyFileSync(path.join(src, "images", f), path.join(out, "images", f));
  }
}

// ---------------------------------------------------------------- tour viewer bundle
async function buildTour() {
  const entry = path.join(ROOT, "client", "tour", "main.js");
  if (!fs.existsSync(entry)) return false;
  await build({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    minify: true,
    target: ["es2020"],
    legalComments: "linked",
    outfile: path.join(ROOT, "public", "js", "tour.bundle.js"),
    logLevel: "warning",
  });
  return true;
}

const STEPS = ["fonts", "leaflet", "tour"];
const asked = process.argv.slice(2);
const unknown = asked.filter((a) => !STEPS.includes(a));
if (unknown.length) {
  console.error(`vendor: unknown step "${unknown[0]}" (use: ${STEPS.join(", ")})`);
  process.exit(1);
}
const run = (step) => !asked.length || asked.includes(step);

const done = [];
if (run("fonts")) done.push(`${buildFonts()} font faces`);
if (run("leaflet")) {
  buildLeaflet();
  done.push("leaflet copied");
}
if (run("tour")) done.push(`tour bundle ${(await buildTour()) ? "built" : "skipped (client/tour/main.js missing)"}`);
console.log(`vendor: ${done.join(", ")}`);
