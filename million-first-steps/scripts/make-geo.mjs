// Builds src/data/geo.json — Georgia's outline, regions and the Mtkvari (Kura) river —
// from Natural Earth (public domain, https://www.naturalearthdata.com/about/terms-of-use/).
//
//   node scripts/make-geo.mjs [path/to/natural-earth-geojson-dir]
//
// Without a directory argument the three source files are downloaded from the
// Natural Earth GitHub mirror. You only need to run this if you want to rebuild the map data.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "src", "data", "geo.json");
const srcDir = process.argv[2];
const base = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/";
const files = {
  countries: "ne_10m_admin_0_countries.geojson",
  regions: "ne_10m_admin_1_states_provinces.geojson",
  rivers: "ne_10m_rivers_lake_centerlines.geojson",
};

async function load(name) {
  if (srcDir) return JSON.parse(fs.readFileSync(path.join(srcDir, name), "utf8"));
  const res = await fetch(base + name);
  if (!res.ok) throw new Error(`Download failed for ${name}: ${res.status}`);
  return res.json();
}

// Equirectangular projection tuned for 42.3°N; keep in sync with src/lib/map.mjs.
export const PROJ = { lon0: 39.9, lat0: 43.68, k: 190, cos: Math.cos((42.3 * Math.PI) / 180), pad: 12 };
const project = ([lon, lat]) => [
  +((lon - PROJ.lon0) * PROJ.cos * PROJ.k + PROJ.pad).toFixed(1),
  +((PROJ.lat0 - lat) * PROJ.k + PROJ.pad).toFixed(1),
];

// Douglas–Peucker simplification in projected units.
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy);
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      // Closed rings start and end on the same point, so fall back to point distance.
      const d = len
        ? Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len
        : Math.hypot(pts[i][0] - ax, pts[i][1] - ay);
      if (d > max) (max = d), (idx = i);
    }
    if (max > tol) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const ringToPath = (ring, tol) =>
  "M" + simplify(ring.map(project), tol).map((p) => p.join(",")).join("L") + "Z";
const polys = (g) => (g.type === "MultiPolygon" ? g.coordinates : [g.coordinates]);

const [countries, regions, rivers] = await Promise.all([
  load(files.countries),
  load(files.regions),
  load(files.rivers),
]);

const georgia = countries.features.find((f) => f.properties.ADMIN === "Georgia");
const outline = polys(georgia.geometry).map((p) => ringToPath(p[0], 0.6)).join("");

const regionPaths = regions.features
  .filter((f) => f.properties.adm0_a3 === "GEO")
  .map((f) => ({
    name: f.properties.name_en || f.properties.name,
    d: polys(f.geometry).map((p) => ringToPath(p[0], 0.8)).join(""),
  }));

// Mtkvari / Kura — keep only the stretches that run inside Georgia's outline.
const inside = ([x, y], ring) => {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const georgiaRing = polys(georgia.geometry)[0][0];
const riverPaths = rivers.features
  .filter((f) => f.properties.name === "Kura")
  .flatMap((f) => (f.geometry.type === "MultiLineString" ? f.geometry.coordinates : [f.geometry.coordinates]))
  .flatMap((line) => {
    const runs = [[]];
    for (const pt of line) {
      if (inside(pt, georgiaRing)) runs[runs.length - 1].push(pt);
      else if (runs[runs.length - 1].length) runs.push([]);
    }
    return runs.filter((r) => r.length > 2);
  })
  .map((l) => "M" + simplify(l.map(project), 0.6).map((p) => p.join(",")).join("L"));

const [w, h] = project([46.75, 41.0]);
const data = {
  source: "Natural Earth 1:10m (public domain). Generated by scripts/make-geo.mjs.",
  projection: PROJ,
  viewBox: `0 0 ${Math.ceil(w + PROJ.pad)} ${Math.ceil(h + PROJ.pad)}`,
  outline,
  regions: regionPaths,
  rivers: riverPaths,
};
fs.writeFileSync(out, JSON.stringify(data));
console.log(`Wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1024).toFixed(1)} KB)`);
